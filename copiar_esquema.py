"""
Copia la ESTRUCTURA (y opcionalmente los DATOS) de la base de producción a la base de prueba.

Uso (desde la carpeta del proyecto, con el venv activado):
    python copiar_esquema.py              # solo estructura (tablas vacías)
    python copiar_esquema.py --datos      # estructura + copia de los datos
    python copiar_esquema.py --datos --reemplazar   # borra las tablas de PRUEBA y vuelve a copiar

Lee de .env.local:
    ORIGEN_DATABASE_URL  → producción (se abre en SOLO LECTURA)
    DATABASE_URL         → prueba (destino)

Seguridad:
  - La sesión contra producción es read-only: no puede modificar nada.
  - Se niega si origen y destino apuntan a la misma base / mismo proyecto.
  - Se niega si el destino ya tiene tablas, salvo --reemplazar (que solo borra en el destino).
  - No copia audit_log (el log se regenera solo en la base de prueba).
  - Las funciones/triggers de auditoría los crea la app al arrancar (ensure_auditoria).
"""
import io
import re
import sys

import psycopg2
import psycopg2.extensions

import entorno_local

TABLAS_SIN_DATOS = {"audit_log"}


def _ident(dsn: str):
    p = psycopg2.extensions.parse_dsn(dsn)
    return (p.get("host", "").lower(), str(p.get("port", "5432")), p.get("dbname", ""), p.get("user", "").lower())


def _refs(dsn: str) -> set:
    return set(re.findall(r"[a-z]{20,}", dsn.lower()))


def _q(nombre: str) -> str:
    return '"' + nombre.replace('"', '""') + '"'


def leer_estructura(cur):
    cur.execute("""
        SELECT c.oid, c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname""")
    tablas = cur.fetchall()

    # Tipos enum propios
    cur.execute("""
        SELECT t.typname, array_agg(e.enumlabel ORDER BY e.enumsortorder)
        FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid
        JOIN pg_namespace n ON n.oid = t.typnamespace
        WHERE n.nspname = 'public' GROUP BY t.typname""")
    enums = cur.fetchall()

    # Secuencias sueltas (serial), excluyendo las internas de columnas IDENTITY
    cur.execute("""
        SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relkind = 'S'
          AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid = c.oid AND d.deptype = 'i')""")
    secuencias = [r[0] for r in cur.fetchall()]

    estructura = []
    for oid, nombre in tablas:
        cur.execute("""
            SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
                   pg_get_expr(d.adbin, d.adrelid), a.attidentity, a.attgenerated
            FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
            WHERE a.attrelid = %s AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum""", (oid,))
        columnas = cur.fetchall()
        cur.execute("""
            SELECT conname, contype, pg_get_constraintdef(oid) FROM pg_constraint
            WHERE conrelid = %s ORDER BY contype, conname""", (oid,))
        restricciones = cur.fetchall()
        cur.execute("""
            SELECT i.indexdef FROM pg_indexes i
            WHERE i.schemaname = 'public' AND i.tablename = %s
              AND i.indexname NOT IN (SELECT conname FROM pg_constraint WHERE conrelid = %s)""",
                    (nombre, oid))
        indices = [r[0] for r in cur.fetchall()]
        estructura.append({"nombre": nombre, "columnas": columnas,
                           "restricciones": restricciones, "indices": indices})

    cur.execute("""
        SELECT t.tgname, c.relname FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND NOT t.tgisinternal AND t.tgname <> 'zz_auditoria'""")
    triggers_extra = cur.fetchall()
    return enums, secuencias, estructura, triggers_extra


def ddl_tabla(t) -> str:
    defs = []
    for nombre, tipo, notnull, default, identity, generated in t["columnas"]:
        col = f"{_q(nombre)} {tipo}"
        if generated == "s":
            col += f" GENERATED ALWAYS AS ({default}) STORED"
        elif identity == "a":
            col += " GENERATED ALWAYS AS IDENTITY"
        elif identity == "d":
            col += " GENERATED BY DEFAULT AS IDENTITY"
        elif default is not None:
            col += f" DEFAULT {default}"
        if notnull:
            col += " NOT NULL"
        defs.append(col)
    return f"CREATE TABLE public.{_q(t['nombre'])} (\n  " + ",\n  ".join(defs) + "\n)"


def main():
    datos = "--datos" in sys.argv
    reemplazar = "--reemplazar" in sys.argv
    entorno_local.cargar(obligatorias=("ORIGEN_DATABASE_URL", "DATABASE_URL"))
    import os
    origen, destino = os.environ["ORIGEN_DATABASE_URL"], os.environ["DATABASE_URL"]

    if _ident(origen) == _ident(destino) or (_refs(origen) & _refs(destino)):
        raise SystemExit("ABORTADO: ORIGEN_DATABASE_URL y DATABASE_URL parecen la MISMA base. "
                         "DATABASE_URL tiene que ser la del proyecto de prueba.")

    src = psycopg2.connect(origen)
    src.set_session(readonly=True)
    dst = psycopg2.connect(destino)
    print(f"Origen  (solo lectura): {_ident(origen)[0]} / {_ident(origen)[3]}")
    print(f"Destino (prueba):       {_ident(destino)[0]} / {_ident(destino)[3]}")

    with src.cursor() as cs:
        enums, secuencias, estructura, triggers_extra = leer_estructura(cs)
    print(f"Tablas en producción: {len(estructura)}")

    with dst.cursor() as cd:
        cd.execute("""SELECT c.relname FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
                      WHERE n.nspname = 'public' AND c.relkind = 'r'""")
        existentes = [r[0] for r in cd.fetchall()]
        if existentes and not reemplazar:
            raise SystemExit(f"ABORTADO: la base de prueba ya tiene {len(existentes)} tablas "
                             f"({', '.join(existentes[:5])}...). Usá --reemplazar para borrarlas y copiar de nuevo.")
        if existentes:
            print(f"Borrando {len(existentes)} tablas de la base de PRUEBA...")
            for nombre in existentes:
                cd.execute(f"DROP TABLE IF EXISTS public.{_q(nombre)} CASCADE")
            cd.execute("DROP FUNCTION IF EXISTS public.audit_registrar() CASCADE")

        for nombre, etiquetas in enums:
            cd.execute(f"DROP TYPE IF EXISTS public.{_q(nombre)} CASCADE")
            cd.execute(f"CREATE TYPE public.{_q(nombre)} AS ENUM (" +
                       ", ".join(cd.mogrify("%s", (e,)).decode() for e in etiquetas) + ")")
        for s in secuencias:
            cd.execute(f"CREATE SEQUENCE IF NOT EXISTS public.{_q(s)}")

        for t in estructura:
            cd.execute(ddl_tabla(t))
            for conname, contype, definicion in t["restricciones"]:
                if contype != "f":
                    cd.execute(f"ALTER TABLE public.{_q(t['nombre'])} ADD CONSTRAINT {_q(conname)} {definicion}")
            for idx in t["indices"]:
                cd.execute(idx)
        print("Estructura creada.")

        if datos:
            for t in estructura:
                if t["nombre"] in TABLAS_SIN_DATOS:
                    continue
                cols = ", ".join(_q(c[0]) for c in t["columnas"] if c[5] != "s")
                buf = io.StringIO()
                with src.cursor() as cs:
                    cs.copy_expert(f"COPY (SELECT {cols} FROM public.{_q(t['nombre'])}) TO STDOUT", buf)
                buf.seek(0)
                cd.copy_expert(f"COPY public.{_q(t['nombre'])} ({cols}) FROM STDIN", buf)
                cd.execute(f"SELECT COUNT(*) FROM public.{_q(t['nombre'])}")
                print(f"  {t['nombre']}: {cd.fetchone()[0]} filas")
            # Ajustar secuencias / identity al máximo id copiado
            for t in estructura:
                for nombre, _tipo, _nn, default, identity, generated in t["columnas"]:
                    if identity or (default or "").startswith("nextval("):
                        cd.execute("SELECT pg_get_serial_sequence(%s, %s)",
                                   (f"public.{_q(t['nombre'])}", nombre))
                        seq = cd.fetchone()[0]
                        if seq:
                            cd.execute(f"SELECT setval(%s, COALESCE(MAX({_q(nombre)}), 1), MAX({_q(nombre)}) IS NOT NULL) "
                                       f"FROM public.{_q(t['nombre'])}", (seq,))

        # Claves foráneas al final (así el orden de copia no importa)
        for t in estructura:
            for conname, contype, definicion in t["restricciones"]:
                if contype == "f":
                    cd.execute(f"ALTER TABLE public.{_q(t['nombre'])} ADD CONSTRAINT {_q(conname)} {definicion}")

    dst.commit()
    src.rollback()
    src.close()
    dst.close()
    print("Listo." + ("" if datos else " (solo estructura; usá --datos para copiar también los datos)"))
    if triggers_extra:
        print("AVISO: producción tiene triggers que no se copiaron:",
              ", ".join(f"{t}@{tb}" for t, tb in triggers_extra))


if __name__ == "__main__":
    main()
